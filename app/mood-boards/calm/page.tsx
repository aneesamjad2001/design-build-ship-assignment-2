function Tile({
  span = "",
  className = "",
  label,
  labelClass = "text-[var(--muted)]",
  children,
}: {
  span?: string;
  className?: string;
  label?: string;
  labelClass?: string;
  children?: React.ReactNode;
}) {
  return (
    <figure
      className={`relative flex flex-col overflow-hidden rounded-[14px] ${span} ${className}`}
    >
      {children}
      {label && (
        <figcaption
          className={`absolute bottom-2 left-3 text-[11px] tracking-wide ${labelClass}`}
        >
          {label}
        </figcaption>
      )}
    </figure>
  );
}

function Swatch({
  hex,
  name,
  span,
  dark = false,
}: {
  hex: string;
  name: string;
  span?: string;
  dark?: boolean;
}) {
  return (
    <Tile span={span} className="border border-black/10">
      <div className="flex-1" style={{ backgroundColor: hex }} />
      <div
        className={`px-3 py-2 text-[11px] tracking-wide ${
          dark ? "text-[var(--bg)]" : "text-[var(--muted)]"
        }`}
        style={{ backgroundColor: hex }}
      >
        {name} · {hex}
      </div>
    </Tile>
  );
}

